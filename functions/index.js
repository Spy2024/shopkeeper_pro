const { onRequest } = require('firebase-functions/v2/https');
const admin = require('firebase-admin');

admin.initializeApp();
const db = admin.firestore();

// The high-entropy tracking token is a bearer capability. Return only status
// and location history; never expose customer names, addresses, UID or finances.
exports.trackCargo = onRequest({ cors: true, maxInstances: 10 }, async (req, res) => {
  res.set('Cache-Control', 'no-store');
  res.set('X-Content-Type-Options', 'nosniff');
  if (req.method !== 'GET') return res.status(405).json({ error: 'method_not_allowed' });

  const token = typeof req.query.token === 'string' ? req.query.token : '';
  // Two concatenated UUIDv4 values generated by the Flutter app.
  if (!/^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(token)) {
    return res.status(400).json({ error: 'invalid_tracking_token' });
  }

  try {
    const matches = await db.collectionGroup('cargo_jobs')
      .where('trackingToken', '==', token).limit(1).get();
    if (matches.empty) return res.status(404).json({ error: 'tracking_not_found' });

    const cargo = matches.docs[0];
    const history = await cargo.ref.parent.parent.collection('cargo_status_history')
      .where('cargoId', '==', cargo.id).orderBy('recordedAt', 'desc').limit(10).get();

    return res.status(200).json({
      status: cargo.get('status') || 'unknown',
      updates: history.docs.map(doc => ({
        status: doc.get('status') || 'unknown',
        location: doc.get('location') || null,
        updatedAt: doc.get('recordedAt') || null
      }))
    });
  } catch (error) {
    console.error('Cargo tracking lookup failed', error);
    return res.status(500).json({ error: 'tracking_temporarily_unavailable' });
  }
});
